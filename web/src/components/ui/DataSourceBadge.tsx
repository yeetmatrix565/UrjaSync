'use client';

import { cx } from '@/lib/format';

/**
 * Where a number came from. This is the honesty mechanism of the whole app:
 * every displayed value must be attributable, and simulated output must never be
 * dressed up as a measurement.
 */
export type DataSource = 'LIVE' | 'DERIVED' | 'SIMULATED' | 'UNAVAILABLE';

const STYLES: Record<DataSource, { label: string; className: string; title: string }> = {
  LIVE: {
    label: 'live',
    className: 'border-brand-green/30 bg-brand-green/10 text-brand-green',
    title: 'Measured by the device and published to ThingSpeak',
  },
  DERIVED: {
    label: 'derived',
    className: 'border-cyan-300/30 bg-cyan-300/10 text-cyan-200',
    title: 'Computed from live measurements by this app',
  },
  SIMULATED: {
    label: 'simulated',
    className: 'border-brand-violet/40 bg-brand-violet/15 text-violet-200',
    title: 'Generated by the simulator, not measured',
  },
  UNAVAILABLE: {
    label: 'not published',
    className: 'border-white/15 bg-white/5 text-white/60',
    title: 'This channel does not publish this metric',
  },
};

export function DataSourceBadge({
  source,
  className,
}: {
  source: DataSource;
  className?: string;
}) {
  const style = STYLES[source];
  return (
    <span
      title={style.title}
      className={cx(
        'shrink-0 rounded-full border px-1.5 py-0.5 font-mono text-[9px] font-medium uppercase tracking-widest',
        style.className,
        className,
      )}
    >
      {style.label}
    </span>
  );
}
